/* =====================================================================
   02_load_data.sql
   Loads 12 monthly "Full CSV data file" extracts (FY 2025/26) into stg_rtt.

   BEFORE RUNNING:
   1. Download the 12 "Full CSV data file" ZIPs (Apr25 ... Mar26) from
      https://www.england.nhs.uk/statistics/statistical-work-areas/rtt-waiting-times/rtt-data-2025-26/
   2. Unzip them into the project's data/ folder and rename each CSV to the
      pattern used below (e.g. rtt_Apr25.csv). data/ is git-ignored.
   3. Replace {DATA_DIR} below with the full path to your data folder,
      using forward slashes, e.g. C:/Users/you/nhs-rtt-waiting-list-analysis/data
   4. Enable local file loading (see docs/SETUP.md) if MySQL refuses the load.

   HOW IT WORKS:
   Each CSV has 104 weekly wait bands (0-1 wks ... 103-104 wks) plus a
   ">104 weeks" band. Instead of storing 105 columns, each band is read into
   a user variable (@b000 ... @b104) and summed on the way in into five
   business-friendly buckets. Blank cells are treated as 0.
     wait_00_18_wks   = bands 0-17   (0 to 18 weeks: the NHS constitutional standard)
     wait_18_52_wks   = bands 18-51
     wait_52_65_wks   = bands 52-64
     wait_65_78_wks   = bands 65-77
     wait_78_plus_wks = bands 78-104 (78+ weeks, including >104)
   ===================================================================== */

